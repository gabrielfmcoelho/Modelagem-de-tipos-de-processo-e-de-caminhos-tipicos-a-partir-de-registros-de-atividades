_NOTE = re.compile(r"\\par\\vspace\{2pt\}\\footnotesize\\raggedright (.*)")


def _bounded(key):
    lead = r"(?<![-\\A-Za-z])" if key[:1].isalnum() else ""
    tail = r"(?![-A-Za-z])" if key[-1:].isalnum() else ""
    return lead + re.escape(key) + tail


_PT_RE = re.compile("|".join(_bounded(k) for k in sorted(PT, key=len, reverse=True)))


def _to_pt_numbers(s):
    s = _THOUSANDS.sub("\x02", s)
    s = _DECIMAL.sub(",", s)
    return s.replace("\x02", ".")


def to_pt(body):
    hidden = []

    def keep(m):
        hidden.append(m.group(0))
        return f"\x00{len(hidden) - 1}\x01"

    out = _SECREF.sub(keep, _PT_RE.sub(lambda m: PT[m.group(0)], _PROTECT.sub(keep, body)))
    return _fit_wide(_HIDDEN.sub(lambda m: hidden[int(m.group(1))], _to_pt_numbers(out)))


def _fit_wide(body):
    m = re.search(r"\\label\{(tab:[a-z-]+)\}", body)
    if not m or m.group(1) not in WIDE_LABELS:
        return body
    body = re.sub(r"(\\begin\{tabular\}.*?\\end\{tabular\})",
                  r"\\resizebox{\\textwidth}{!}{%\n\1\n}", body, count=1, flags=re.S)
    if "\\footnotesize" not in body:
        body = body.replace("\\resizebox{", "\\footnotesize\n\\resizebox{", 1)
    return body


def untranslated(body):
    strings = [m.group(1) for m in _CAPTION.finditer(body)]
    strings += [cell for m in _HEADER_ROW.finditer(body) for cell in m.group(1).split(" & ")]
    strings += [m.group(1) for m in _NOTE.finditer(body)]
    gaps = {}
    for s in dict.fromkeys(strings):
        rest, pos = [], 0
        for m in _PT_RE.finditer(s):
            rest.append(s[pos:m.start()])
            pos = m.end()
        rest.append(s[pos:])
        words = sorted({w for r in rest for w in _WORD.findall(_MACRO.sub(" ", r))})
        if words:
            gaps[s] = words
    return gaps


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--figures", default=str(FIGURES))
    ap.add_argument("--out")
    ap.add_argument("--lang", choices=("en", "pt"), default="en")
    args = ap.parse_args()

    figures = json.loads(Path(args.figures).read_text(encoding="utf-8"))
    out = Path(args.out or (OUT if args.lang == "en" else OUT_PT))
    out.mkdir(parents=True, exist_ok=True)
    written, gaps = [], []
    for name, fn in TABLES.items():
        body = fn(figures)
        if not body.strip():
            raise RuntimeError(f"gen_tables_tex: {name} rendered empty")
        if args.lang == "pt":
            gaps += [(name, s, w) for s, w in untranslated(body).items()]
            body = to_pt(body)
        (out / f"{name}.tex").write_text(HEADER + body, encoding="utf-8")
        written.append(name)
    print(f"wrote {len(written)} LaTeX tables to {out}: {', '.join(written)}")
    for name, s, words in gaps:
        print(f"  no PT entry: [{name}] {s!r} -> {', '.join(words)}")
    return 0


